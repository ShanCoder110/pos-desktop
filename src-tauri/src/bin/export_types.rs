//! Export ts-rs bindings for API DTOs into `src/types/generated/`.
//! Run from repo root: `npm run types:generate`

use std::path::PathBuf;

use tauri_app_lib::backend::dto::{
    AuthStatusResponse, LoginRequest, LoginResponse, LogoutResponse, MeResponse, RefreshRequest,
    SetupRequest, UserPermissionResponse, UserResponse,
};
use ts_rs::TS;

fn main() {
    let out = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../src/types/generated");
    std::fs::create_dir_all(out.join("auth")).expect("create generated types dir");

    LoginRequest::export_all_to(&out).expect("export LoginRequest");
    LoginResponse::export_all_to(&out).expect("export LoginResponse");
    AuthStatusResponse::export_all_to(&out).expect("export AuthStatusResponse");
    SetupRequest::export_all_to(&out).expect("export SetupRequest");
    RefreshRequest::export_all_to(&out).expect("export RefreshRequest");
    MeResponse::export_all_to(&out).expect("export MeResponse");
    LogoutResponse::export_all_to(&out).expect("export LogoutResponse");
    UserResponse::export_all_to(&out).expect("export UserResponse");
    UserPermissionResponse::export_all_to(&out).expect("export UserPermissionResponse");

    std::fs::write(
        out.join("index.ts"),
        r#"/** AUTO-GENERATED by `npm run types:generate` — do not edit by hand. */
export type { LoginRequest } from "./auth/LoginRequest";
export type { LoginResponse } from "./auth/LoginResponse";
export type { AuthStatusResponse } from "./auth/AuthStatusResponse";
export type { SetupRequest } from "./auth/SetupRequest";
export type { RefreshRequest } from "./auth/RefreshRequest";
export type { MeResponse } from "./auth/MeResponse";
export type { LogoutResponse } from "./auth/LogoutResponse";
export type { UserResponse } from "./auth/UserResponse";
export type { UserPermissionResponse } from "./auth/UserPermissionResponse";
"#,
    )
    .expect("write index.ts");

    println!("Exported TS types to {}", out.display());
}
